def _flag(country: str, home: str) -> str:
    cls = "home" if country == home else ("unknown" if country == "??" else "abroad")
    label = {"home": country, "unknown": "unknown country", "abroad": f"{country} · outside {home}"}[cls]
    return f'<span class="flag {cls}">{html.escape(label)}</span>'


def html_report(run: dict, home: str) -> str:
    e = html.escape
    receivers = _receivers(run, home)
    abroad = [p for p in receivers if p["country"] != home]
    kinds = {cat for p in receivers for cat in p["data"]}
    cards = []
    for p in receivers:
        rows = "".join(
            f"<tr><td>{e(d['label'])}</td><td>{'<br>'.join(f'<code>{e(f)}</code>' for f in d['fields'])}</td>"
            f"<td><code>{e(d['example'])}</code></td><td><code>{e(d['endpoint'])}</code></td></tr>"
            for d in p["data"].values()
        )
        cards.append(
            f'<section class="card"><h2>{e(p["name"])} {_flag(p["country"], home)}</h2>'
            f'<p class="meta">{e(p["kind"])} · {e(", ".join(p["hosts"]))} · {p["requests"]} request(s)</p>'
            f"<table><tr><th>Data</th><th>Field</th><th>Example (masked)</th><th>Seen at</th></tr>{rows}</table></section>"
        )
    quiet = [p["name"] for p in run["processors"] if not p["data"]]
    quiet_html = f'<p class="quiet">Contacted, no personal data seen: {e(", ".join(quiet))}</p>' if quiet else ""
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>leakmap report</title><style>{_CSS}</style></head>
<body><main>
<h1>{e(headline(run, home))}</h1>
<p class="sub">{e(_command(run))} · {e(run['created'])} · leakmap {e(run['leakmap'])}</p>
<div class="stats">
<div class="stat"><b>{len(receivers)}</b><span>companies received personal data</span></div>
<div class="stat"><b>{len(abroad)}</b><span>of them outside {e(home)}</span></div>
<div class="stat"><b>{len(kinds)}</b><span>kinds of personal data</span></div>
<div class="stat"><b>{run['events']}</b><span>outgoing requests inspected</span></div>
</div>
{''.join(cards) or '<p>No personal data seen.</p>'}
{quiet_html}
<footer>{e(DISCLAIMER)}</footer>
</main></body></html>
"""


def render(run: dict, fmt: str, home: str) -> str:
    if fmt == "terminal":
        return terminal(run, home)
    if fmt == "md":
        return markdown(run, home)
    if fmt == "html":
        return html_report(run, home)
    if fmt == "dpdp":
        return dpdp(run, home)
    if fmt == "json":
        return json.dumps(run, indent=2) + "\n"
    raise ValueError(f"unknown format {fmt}")
