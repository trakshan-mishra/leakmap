"""Render a run summary for people: terminal, Markdown, HTML, DPDP register, JSON."""

import html
import json
import os
import sys
from pathlib import Path


DISCLAIMER = "leakmap reports what it saw during this run. It is evidence to support a privacy review, not legal advice or a compliance certificate."


def _command(run) -> str:
    cmd = run["command"]
    return " ".join([Path(cmd[0]).name, *cmd[1:]]) if cmd else ""


def _receivers(run, home: str = ""):
    """Recipients of personal data, those outside the home country first."""
    receivers = [p for p in run["processors"] if p["data"]]
    return sorted(receivers, key=lambda p: (p["country"] == home, -len(p["data"])))


def headline(run: dict, home: str) -> str:
    receivers = _receivers(run)
    abroad = [p for p in receivers if p["country"] != home]
    if not receivers:
        return f"No personal data seen in {run['events']} outgoing requests."
    return (f"{len(receivers)} third part{'y' if len(receivers) == 1 else 'ies'} received personal data"
            f" ({len(abroad)} outside {home}) across {run['events']} outgoing requests.")


# --- terminal ---------------------------------------------------------------

def _color(enabled):
    def paint(code, text):
        return f"\033[{code}m{text}\033[0m" if enabled else text
    return paint


def terminal(run: dict, home: str, color: bool | None = None) -> str:
    if color is None:
        color = sys.stdout.isatty() and "NO_COLOR" not in os.environ
    c = _color(color)
    lines = ["", c("1", "leakmap ") + headline(run, home), ""]
    for p in _receivers(run, home):
        tone = "32" if p["country"] == home else ("33" if p["country"] == "??" else "31")
        lines.append(f"  {c('1', p['name'])} {c(tone, '[' + p['country'] + ']')}  {c('2', p['kind'] + ' · ' + ', '.join(p['hosts']))}")
        width = max(len(d["label"]) for d in p["data"].values())
        fwidth = max(len(d["fields"][0]) for d in p["data"].values())
        for d in p["data"].values():
            lines.append(f"    {c(tone, '●')} {d['label']:<{width}}  {c('2', d['fields'][0].ljust(fwidth))}  {d['example']}")
        lines.append("")
    quiet = [p["name"] for p in run["processors"] if not p["data"]]
    if quiet:
        lines.append(c("2", "  Contacted, no personal data seen: " + ", ".join(quiet)))
    uninspected = sum(p["uninspected"] for p in run["processors"])
    if uninspected:
        lines.append(c("33", f"  {uninspected} request(s) had binary or oversized bodies and were not inspected."))
    if run.get("hidden_low_confidence"):
        lines.append(c("2", f"  {run['hidden_low_confidence']} low-confidence match(es) hidden (set min_confidence: low to show)."))
    return "\n".join(lines).rstrip() + "\n"


# --- markdown ---------------------------------------------------------------

def markdown(run: dict, home: str) -> str:
    out = ["# leakmap report", "", f"**{headline(run, home)}**", "",
           f"Command: `{_command(run)}` · {run['created']} · leakmap {run['leakmap']}", ""]
    for p in run["processors"]:
        out.append(f"## {p['name']} ({p['country']})")
        out.append(f"{p['kind']} · {', '.join(p['hosts'])} · {p['requests']} request(s)")
        out.append("")
        if not p["data"]:
            out += ["No personal data seen.", ""]
            continue
        out += ["| Data | Fields | Example | Seen at |", "|---|---|---|---|"]
        for d in p["data"].values():
            out.append(f"| {d['label']} | {'<br>'.join(f'`{f}`' for f in d['fields'])} | `{d['example']}` | `{d['endpoint']}` |")
        out.append("")
    out += ["---", f"_{DISCLAIMER}_", ""]
    return "\n".join(out)


# --- DPDP / GDPR processor register ------------------------------------------

def dpdp(run: dict, home: str) -> str:
    out = [
        "# Data processor register (draft)",
        "",
        f"Generated by leakmap {run['leakmap']} on {run['created']} from: `{_command(run)}`",
        "",
        "Fill in the purpose and the agreement column for each row. Rows come from observed traffic only;",
        "processors your tests did not exercise will be missing.",
        "",
        f"| Processor | Country | Transfer outside {home} | Personal data | Purpose | Agreement / DPA |",
        "|---|---|---|---|---|---|",
    ]
    for p in _receivers(run, home):
        abroad = "Yes" if p["country"] != home else "No"
        out.append(f"| {p['name']} | {p['country']} | {abroad} | {', '.join(d['label'] for d in p['data'].values())} | _to fill_ | _to fill_ |")
    out += ["", f"_{DISCLAIMER}_", ""]
    return "\n".join(out)


